#!/usr/bin/env node
/** Regenerate data/collections.generated.ts from the catalogue + config. */
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const config = JSON.parse(await fs.readFile(path.join(ROOT, "data/collections.config.json"), "utf8"));
const games = JSON.parse(await fs.readFile(path.join(ROOT, "data/games.json"), "utf8"));
const content = await fs.readFile(path.join(ROOT, "data/game-content.ts"), "utf8");
const curated = new Set(
  [...content.split("export const GAME_CONTENT")[1].split("export const FEATURED_SLUGS")[0].matchAll(/^  "([a-z0-9-]+)": \{/gm)].map((m) => m[1])
);

const out = {};
for (const c of config) {
  let pool = games.filter((g) => {
    if (c.filter.category && g.category !== c.filter.category) return false;
    if (c.filter.titleIncludes && !g.title.toLowerCase().includes(c.filter.titleIncludes)) return false;
    return true;
  });
  pool.sort((a, b) => Number(curated.has(b.slug)) - Number(curated.has(a.slug)) || (b.plays ?? 0) - (a.plays ?? 0));
  const picked = pool.slice(0, c.limit).filter((g) => curated.has(g.slug) || pool.filter((x) => curated.has(x.slug)).length < 8);
  out[c.slug] = {
    slug: c.slug,
    title: c.title,
    h1: c.h1,
    description: c.description,
    intro: c.intro,
    faq: c.faq,
    playHref: c.playHref,
    guide: c.guide,
    games: picked.map((g) => ({ slug: g.slug, title: g.title, thumb: g.thumb, category: g.category })),
  };
}

const body = `// Generated by scripts/build-collections.mjs — do not edit by hand.\nexport type CollectionGame = { slug: string; title: string; thumb: string; category: string };\nexport type Collection = {\n  slug: string; title: string; h1: string; description: string; intro: string;\n  faq: { q: string; a: string }[]; playHref: string; guide?: string; games: CollectionGame[];\n};\n\nexport const COLLECTIONS: Record<string, Collection> = ${JSON.stringify(out, null, 2)};\n`;
await fs.writeFile(path.join(ROOT, "data/collections.generated.ts"), body);
for (const [slug, c] of Object.entries(out)) console.log(`${slug}: ${c.games.length} games`);
